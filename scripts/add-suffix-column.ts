async function addSuffixColumn() {
  console.log("Adding suffix column to words table...");

  // Add column if it doesn't exist
  try {
    await db.execute(sql`
      ALTER TABLE words ADD COLUMN IF NOT EXISTS suffix VARCHAR(10)
    `);
    console.log("✅ Column added (or already exists)");
  } catch (error) {
    console.log("Column might already exist:", error);
  }

  // Get all words
  const allWords = await db.select().from(words);
  console.log(`Found ${allWords.length} words in database`);

  let updated = 0;
  let notFound = 0;

  for (const word of allWords) {
    const suffix = WORD_SUFFIXES[word.word];

    if (suffix) {
      await db.execute(sql`
        UPDATE words SET suffix = ${suffix} WHERE id = ${word.id}
      `);
      updated++;
      console.log(`✅ ${word.word} → ${suffix}`);
    } else {
      // Auto-generate 3-letter suffix from the end of the word
      const autoSuffix = word.word.slice(-3).toUpperCase();
      await db.execute(sql`
        UPDATE words SET suffix = ${autoSuffix} WHERE id = ${word.id}
      `);
      updated++;
      console.log(`⚠️ ${word.word} → ${autoSuffix} (auto-generated)`);
      notFound++;
    }
  }

  console.log(`\n✅ Updated ${updated} words`);
  if (notFound > 0) {
    console.log(`⚠️ ${notFound} words had auto-generated suffixes`);
  }

  // Verify
  const result = await db.execute(sql`
    SELECT word, suffix FROM words LIMIT 10
  `);
  console.log("\nSample results:", result.rows);

  process.exit(0);
}

addSuffixColumn();
